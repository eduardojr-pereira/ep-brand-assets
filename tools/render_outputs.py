"""Canonical editorial outputs renderer; project data stays with the project."""
from pathlib import Path
from html import escape
from string import Template
from urllib.parse import urlsplit
ROOT = Path(__file__).resolve().parents[1]
s = (ROOT/'components/web/outputs.html').read_text(encoding='utf-8')
SECTION, rest = s.split('<!-- EP-OUTPUT-ITEM -->')
ITEM, rest = rest.split('<!-- EP-OUTPUT-FIGURES -->')
FIGURES, FIGURE = rest.split('<!-- EP-OUTPUT-FIGURE -->')
def esc(v): return escape(str(v),quote=True)
def bilingual(v):
    if isinstance(v,str): return esc(v)
    en,pt=v['en'],v['pt-BR']
    return f'<span data-ep-out-en="{esc(en)}" data-ep-out-pt="{esc(pt)}">{esc(en)}</span>'
def pair(en,pt): return bilingual({'en':en,'pt-BR':pt})
def url(v):
    p=urlsplit(v)
    if p.scheme or p.netloc or v.startswith('/') or '\\' in v or not p.path:
        raise ValueError(f'Invalid artifact path: {v}')
    return esc(v)
def render_outputs(data):
    items=[]
    for i,item in enumerate(data['items'],1):
        items.append(Template(ITEM).substitute(url=url(item['path']),number=f'{i:02d}',name=bilingual(item['name']),origin=bilingual(item['origin']),description=bilingual(item['description']),format=esc(item['format'])))
    figures=[]
    for item in data.get('figures',[]):
        figures.append(Template(FIGURE).substitute(url=url(item['path']),alt=esc(item['name']['en']),name=bilingual(item['name']),description=bilingual(item['description']),view=pair('View figure','Ver figura')))
    gallery=Template(FIGURES).substitute(title=pair('Additional Figures','Figuras Adicionais'),intro=pair('Supplementary visualizations generated by the original analysis notebook.','Visualizações complementares geradas pelo notebook original de análise.'),cards=''.join(figures)) if figures else ''
    return Template(SECTION).substitute(title=pair('Validated Outputs','Resultados Validados'),intro=pair('Explore the validated metrics, model evaluations and predictions exported from the analysis notebook.','Explore as métricas validadas, avaliações de modelos e predições exportadas pelo notebook de análise.'),artifact=pair('Artifact','Artefato'),format=pair('Format','Formato'),items=''.join(items),figures=gallery)
